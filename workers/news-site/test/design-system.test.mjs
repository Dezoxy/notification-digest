// Tests for scripts/design-system.mjs: the generator that turns this Worker's
// stylesheet into the files of the design-system artifact. Pure — it builds
// the file map in memory and never touches the filesystem or git.
//
// The drift guard is the reason this file exists. buildDesignSystem() parses
// the tokens out of src/css.js (the block between tokens:start and
// tokens:end); if someone adds a custom property there without documenting
// it in the script, building against the real stylesheet throws, and this
// file (so `npm test`) fails.

import { test } from "node:test";
import assert from "node:assert/strict";

import { buildDesignSystem } from "../scripts/design-system.mjs";
import { CSS } from "../src/css.js";
import { FAVICON_SVG } from "../src/chrome.js";
import * as icons from "../src/icons.js";

const NOW = new Date("2026-01-02T03:04:05.678Z");
const build = (css = CSS) =>
  buildDesignSystem({
    css,
    faviconSvg: FAVICON_SVG,
    icons,
    sha: "abc1234",
    by: "tester",
    now: NOW,
  });

const text = (files, path) => {
  const v = files.get(path);
  assert.equal(typeof v, "string", `${path} should be a text file`);
  return v;
};
const colour = (tokens, name) => tokens.color.tokens.find((t) => t.name === name);

test("builds against the real stylesheet; every component has a card and a README", () => {
  const { files, components, audit } = build();
  assert.ok(components.length > 0);
  assert.ok(Object.keys(audit).length > 0);
  for (const name of components) {
    const preview = text(files, `components/${name}/preview.html`);
    assert.match(preview.split("\n")[0], /^<!-- @dsCard /, `${name} preview header`);
    assert.ok(files.has(`components/${name}/README.md`), `${name} README`);
  }
  assert.match(text(files, "components/Cover/preview.html").split("\n")[0], /^<!-- @dsCard /);
  assert.ok(!files.has("components/Cover/README.md"), "the Cover has no README");
  assert.ok(!files.has("tokens.css"), "tokens.css is generated by the artifact page");
});

test("tokens.json resolves both themes from the parsed light-dark() pairs", () => {
  const tokens = JSON.parse(text(build().files, "tokens.json"));
  assert.deepEqual(colour(tokens, "bg").value, { light: "#eceff6", dark: "#0b0d14" });
  assert.deepEqual(colour(tokens, "accent").value, { light: "#4458d8", dark: "#9db0ff" });
  // rgba() has commas of its own: the split must be on the top-level one.
  assert.deepEqual(colour(tokens, "panel").value, {
    light: "rgba(255, 255, 255, 0.66)",
    dark: "rgba(255, 255, 255, 0.055)",
  });
  assert.equal(colour(tokens, "brand-mark").value, "#9db0ff");
  assert.match(tokens.type.families.display, /^"Sora"/);
  assert.match(tokens.type.families.body, /^"Inter"/);
  const gutter = tokens.spacing.tokens.find((t) => t.name === "gutter");
  assert.equal(gutter.value, "32px");
  assert.equal(tokens.radius.tokens.find((t) => t.name === "r-card").value, "24px");
  assert.ok(!JSON.stringify(tokens).includes("light-dark("), "no unresolved pair in tokens.json");
});

test("--shadow resolves per theme: one arm of every inner light-dark()", () => {
  const tokens = JSON.parse(text(build().files, "tokens.json"));
  const shadow = tokens.shadow.tokens.find((t) => t.name === "shadow");
  assert.equal(shadow.value.light, "0 24px 60px rgba(40, 52, 100, 0.13), 0 30px 80px transparent");
  assert.equal(shadow.value.dark, "0 24px 60px transparent, 0 30px 80px rgba(0, 0, 0, 0.38)");
});

test("drift guard: a colour with no usage note fails the build", () => {
  const added = CSS.replace(
    "  :root {\n",
    "  :root {\n    --new-thing: light-dark(#123456, #654321);\n",
  );
  assert.notEqual(added, CSS);
  assert.throws(() => build(added), /new-thing/);
});

test("drift guard: a single-valued token with no usage note fails the build", () => {
  const added = CSS.replace("  :root {\n", "  :root {\n    --new-size: 7px;\n");
  assert.notEqual(added, CSS);
  assert.throws(() => build(added), /new-size/);
});

test("drift guard: a documented token the CSS dropped fails the build", () => {
  const removed = CSS.replace(/^\s*--muted: [^\n]*\n/m, "");
  assert.notEqual(removed, CSS);
  assert.throws(() => build(removed), /muted/);
});

test("drift guard: a themed colour that lost its light-dark() pair fails the build", () => {
  const flat = CSS.replace(/--accent: light-dark\([^;]*\);/, "--accent: #4458d8;");
  assert.notEqual(flat, CSS);
  assert.throws(() => build(flat), /accent/);
});

test("drift guard: a theme block that holds more than color-scheme fails the build", () => {
  const dirty = CSS.replace(
    ':root[data-theme="dark"] { color-scheme: dark; }',
    ':root[data-theme="dark"] { color-scheme: dark; --bg: #000000; }',
  );
  assert.notEqual(dirty, CSS);
  assert.throws(() => build(dirty), /color-scheme/);
});

test("bundle.css carries no token block and cannot close a <style> block", () => {
  const bundle = text(build().files, "components/bundle.css");
  assert.ok(!bundle.includes("--bg:"));
  assert.ok(!bundle.includes("tokens:start"));
  assert.ok(!/<\/style/i.test(bundle));
  assert.ok(bundle.includes("@ abc1234"));
});

test("design-system.json is the files-layout index", () => {
  const index = JSON.parse(text(build().files, "design-system.json"));
  assert.equal(index.v, 3);
  assert.equal(index.layout, "files");
  assert.equal(typeof index.createdOnFiles, "object");
  assert.equal(index.lastChange.by, "tester");
  assert.equal(index.lastChange.at, "2026-01-02T03:04:05Z");
  assert.ok(!JSON.stringify(index).includes("claude.ai"));
});
