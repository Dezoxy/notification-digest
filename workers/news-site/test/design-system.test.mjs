// Tests for scripts/design-system.mjs: the generator that turns this Worker's
// stylesheet into the files of the design-system artifact. Pure — it builds
// the file map in memory and never touches the filesystem or git.
//
// The drift guard is the reason this file exists. buildDesignSystem() parses
// the palette out of src/css.js; if someone adds a custom property there
// without documenting it in the script, building against the real stylesheet
// throws, and this file (so `npm test`) fails.

import { test } from "node:test";
import assert from "node:assert/strict";

import { buildDesignSystem } from "../scripts/design-system.mjs";
import { CSS } from "../src/css.js";
import { FAVICON_SVG } from "../src/chrome.js";
import * as icons from "../src/icons.js";

const NOW = new Date("2026-01-02T03:04:05.678Z");
const build = (css = CSS) =>
  buildDesignSystem({
    css,
    faviconSvg: FAVICON_SVG,
    icons,
    sha: "abc1234",
    by: "tester",
    now: NOW,
  });

const text = (files, path) => {
  const v = files.get(path);
  assert.equal(typeof v, "string", `${path} should be a text file`);
  return v;
};
const colour = (tokens, name) => tokens.color.tokens.find((t) => t.name === name);

test("builds against the real stylesheet; every component has a card and a README", () => {
  const { files, components, audit } = build();
  assert.ok(components.length > 0);
  assert.ok(Object.keys(audit).length > 0);
  for (const name of components) {
    const preview = text(files, `components/${name}/preview.html`);
    assert.match(preview.split("\n")[0], /^<!-- @dsCard /, `${name} preview header`);
    assert.ok(files.has(`components/${name}/README.md`), `${name} README`);
  }
  assert.match(text(files, "components/Cover/preview.html").split("\n")[0], /^<!-- @dsCard /);
  assert.ok(!files.has("components/Cover/README.md"), "the Cover has no README");
  assert.ok(!files.has("tokens.css"), "tokens.css is generated by the artifact page");
});

test("tokens.json colours come from the parsed CSS", () => {
  const tokens = JSON.parse(text(build().files, "tokens.json"));
  assert.deepEqual(colour(tokens, "bg").value, { light: "#ffffff", dark: "#131418" });
  assert.deepEqual(colour(tokens, "accent").value, { light: "#0e3fa9", dark: "#7d9bff" });
  assert.deepEqual(colour(tokens, "prose").value, { light: "#3d4350", dark: "#c3c9d4" });
  assert.deepEqual(colour(tokens, "chip-text").value, { light: "{accent}", dark: "{accent}" });
  assert.deepEqual(colour(tokens, "h2-border").value, { light: "{accent}", dark: "{accent}" });
  assert.equal(colour(tokens, "brand-mark").value, "#4f46e5");
  assert.equal(
    tokens.type.families.prose,
    'ui-sans-serif, system-ui, -apple-system, "Helvetica Neue", sans-serif',
  );
  const fab = tokens.spacing.tokens.find((t) => t.name === "fab-size");
  assert.equal(fab.value, "48px");
});

test("drift guard: a palette variable with no usage note fails the build", () => {
  const added = CSS.replace("  :root {\n", "  :root {\n    --new-thing: #123456;\n");
  assert.notEqual(added, CSS);
  assert.throws(() => build(added), /new-thing/);
});

test("drift guard: a documented variable the CSS dropped fails the build", () => {
  const removed = CSS.replace(/^\s*--faint: [^\n]*\n/m, "");
  assert.notEqual(removed, CSS);
  assert.throws(() => build(removed), /faint/);
});

test("drift guard: an alias that stopped matching accent fails the build", () => {
  const diverged = CSS.replace("--chip-text: #0e3fa9;", "--chip-text: #0e3faa;");
  assert.notEqual(diverged, CSS);
  assert.throws(() => build(diverged), /chip-text/);
});

test("bundle.css carries no palette definition and cannot close a <style> block", () => {
  const bundle = text(build().files, "components/bundle.css");
  assert.ok(!bundle.includes("--bg:"));
  assert.ok(!/<\/style/i.test(bundle));
  assert.ok(bundle.includes("@ abc1234"));
});

test("design-system.json is the files-layout index", () => {
  const index = JSON.parse(text(build().files, "design-system.json"));
  assert.equal(index.v, 3);
  assert.equal(index.layout, "files");
  assert.equal(typeof index.createdOnFiles, "object");
  assert.equal(index.lastChange.by, "tester");
  assert.equal(index.lastChange.at, "2026-01-02T03:04:05Z");
  assert.ok(!JSON.stringify(index).includes("claude.ai"));
});
