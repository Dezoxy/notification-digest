// Fail-safe slug->section mapping for arc-page deep links (§11.1 guardrail:
// "a wrong deep link is worse than a missing one"). Runs the exact same
// stripInlineStyles -> buildSectionToc pipeline renderDigestPage itself runs
// on body_html (see there) so the #sN ids this produces line up byte-for-
// byte with what that digest's OWN page actually renders — this is never
// reimplemented or approximated, just re-run on the same input.
//
// Always the ENGLISH body_html, never body_html_hu, regardless of which
// language this arc page is being read in: derive_topics (notification-
// digest repo, digest/publish.py) derives every topic label from the
// English body_md's own `## ` headings, so an English heading is the only
// text a topic label can ever have come from — matching against the HU
// translation's (differently worded) headings would just never match.
//
// Exact match preferred (labels under 80 chars are never truncated, so the
// heading and the label are identical strings); falls back to startsWith
// (the label IS the heading truncated to 80 chars — see derive_topics) only
// when that resolves to exactly one candidate. Zero or multiple candidates
// (ambiguous — two sections whose text happens to collide) both return
// null, which renders as a fragment-less link to the digest page itself
// (see renderArcAppearance) rather than a guess that might land on the
// wrong section.
// Split in two so the expensive half runs once per BODY and the cheap half
// once per APPEARANCE: sectionsOfBody is the full stripInlineStyles ->
// buildSectionToc regex pipeline over a body that can be megabytes, and an
// arc revisiting the same digest under several labels used to re-run it for
// every appearance (up to ARC_ANCHOR_BODIES times per page view).
export function sectionsOfBody(bodyHtml) {
  return buildSectionToc(stripInlineStyles(bodyHtml)).sections;
}

export function findArcSectionAnchor(sections, label) {
  const trimmed = label.trim();
  const exact = sections.filter((s) => s.title === trimmed);
  if (exact.length === 1) return exact[0].id;
  if (exact.length > 1) return null;
  const partial = sections.filter((s) => s.title.startsWith(trimmed));
  return partial.length === 1 ? partial[0].id : null;
}

// Section index (TOC, roadmap step 5): scan the article body actually being
// shown (EN or HU — the caller passes whichever articleHtml it already
// resolved) for bare, attribute-free `<h2>title</h2>` headings. nh3 strips
// attributes upstream, so a real section heading arrives in exactly that
// shape; an h2 with any attribute or nested tag doesn't match `[^<]*` and is
// silently skipped — failing safe on an unexpected shape rather than
// guessing at it.
//
// The `.attention` callout's own h2 must never become a TOC entry: split the
// html on that div first (non-greedy — the div isn't expected to nest) and
// only scan/inject the segments outside it, passing the div's own segment
// through byte-for-byte. String.prototype.split with a capturing group
// interleaves the captured separator back into the result at the odd
// indices, so those are exactly the attention-div segments to skip.
//
// ids are "s1".."sN", sequential and positional across the whole article
// (numbering continues across any attention-div gap) — the id VALUE is
// generated by us, never derived from heading text, so no sanitization
// question arises for the id itself; the heading text stays untouched other
// than gaining the id attribute.
export function buildSectionToc(articleHtml) {
  const parts = articleHtml.split(/(<div class="attention">[\s\S]*?<\/div>)/);
  const sections = [];
  let n = 0;
  const html = parts
    .map((part, i) => {
      if (i % 2 === 1) return part; // attention-div segment: pass through
      return part.replace(/<h2>([^<]*)<\/h2>/g, (_match, title) => {
        n += 1;
        const id = `s${n}`;
        sections.push({ id, title: title.trim() });
        return `<h2 id="${id}">${title}</h2>`;
      });
    })
    .join("");
  return { html, sections };
}

const FOLD_BLOCK_TAGS = ["p", "ul", "ol", "div", "blockquote", "table"];

// True when every block tag opens and closes equally often in `segment`.
// Fold wraps segments in new containers, so a stray unclosed <p>/<div> would
// swallow the next section's chrome; counting is crude but errs toward
// refusing, which is the safe direction.
function blocksBalanced(segment) {
  return FOLD_BLOCK_TAGS.every((tag) => {
    const open = (segment.match(new RegExp(`<${tag}(?=[\\s>])`, "g")) ?? []).length;
    const close = (segment.match(new RegExp(`</${tag}>`, "g")) ?? []).length;
    return open === close;
  });
}

// One-line teaser for a folded section: first paragraph's text, citation
// chips dropped (their superscript digits read as noise), tags stripped but
// entities left escaped — the source is already-sanitized html, so the text
// stays valid to re-insert as-is. Cut at a word boundary, never inside an
// `&entity;`.
function sectionPreview(chunk, max = 140) {
  const p = chunk.match(/<p(?:\s[^>]*)?>([\s\S]*?)<\/p>/);
  if (!p) return "";
  const text = p[1]
    .replace(/<a class="cite"[^>]*>[\s\S]*?<\/a>/g, "")
    .replace(/<[^>]*>/g, "")
    .replace(/\s+/g, " ")
    .trim();
  if (text.length <= max) return text;
  let cut = text.slice(0, max);
  const amp = cut.lastIndexOf("&");
  if (amp > cut.lastIndexOf(";")) cut = cut.slice(0, amp);
  const space = cut.lastIndexOf(" ");
  if (space > 0) cut = cut.slice(0, space);
  return `${cut.replace(/[\s,;:.\-–—]+$/, "")}…`;
}

// Each section starts as an open native disclosure. A reader who collapses
// it still sees the heading, teaser and citation count. Preserve the h2 and
// its #sN id so section navigation and deep links keep their targets.
//
// `.secarc` (inserted right after an h2) needs no special move: the h2 goes
// into <summary>, the link stays first in .secbody — interactive content
// inside <summary> is an accessibility problem.
//
// Everything before the first h2 (banner, .tldr, .attention) and the closing
// p.foot stay outside any <details>. Fail-safe: any unbalanced segment, any
// stray <h2>, or a count differing from the TOC's returns `html` unchanged.
export function foldSections(html, sectionCount, strings) {
  const heads = [...html.matchAll(/<h2 id="s\d+">[^<]*<\/h2>/g)];
  if (heads.length === 0 || heads.length !== sectionCount) return html;
  if ((html.match(/<h2[\s>]/g) ?? []).length !== heads.length) return html;

  const pre = html.slice(0, heads[0].index);
  const chunks = heads.map((h, i) =>
    html.slice(h.index + h[0].length, i + 1 < heads.length ? heads[i + 1].index : html.length),
  );
  let tail = "";
  const foot = chunks[chunks.length - 1].match(/\s*<p class="foot">[\s\S]*?<\/p>\s*$/);
  if (foot) {
    tail = foot[0];
    chunks[chunks.length - 1] = chunks[chunks.length - 1].slice(0, foot.index);
  }
  if (![pre, tail, ...chunks].every(blocksBalanced)) return html;

  const secs = heads.map((h, i) => {
    const preview = sectionPreview(chunks[i]);
    const cites = (chunks[i].match(/<a class="cite"/g) ?? []).length;
    return (
      `<details class="sec" open><summary class="sechead">${h[0]}` +
      (preview ? `<span class="secpreview" aria-hidden="true">${preview}</span>` : "") +
      (cites
        ? `<span class="seccount">${esc((cites === 1 ? strings.sourceCountOne : strings.sourceCount).replace("{n}", String(cites)))}</span>`
        : "") +
      `</summary><div class="secbody">${chunks[i]}</div></details>`
    );
  });
  return `${pre}${secs.join("\n")}${tail}`;
}

// Remove every style="…" attribute from the article html — see the call
// site in renderDigestPage for the full story (email-oriented inline styles
// fighting the site's theme CSS, and breaking downstream exact-shape
// regexes). Runs on nh3-normalized + emailer-generated markup only, where
// attributes are guaranteed double-quoted.
export function stripInlineStyles(html) {
  return html.replace(/ style="[^"]*"/g, "");
}
